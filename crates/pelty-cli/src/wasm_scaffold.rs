//! `pelty-cli addon wasm-scaffold`: a WASM addon skeleton (Rust tested;
//! C and TinyGo are templates only, not built in CI).
use serde_json::json;
use std::path::{Path, PathBuf};

pub const LANGS: &[&str] = &["rust", "c", "tinygo"];

/// `abi`: 0.5.0 for Rust (SDK `cron` feature, `on-cron` export); the C and
/// TinyGo templates target the 0.4 world.
fn manifest(id: &str, kind: &str, name: &str, abi: &str) -> String {
    let provides = id.rsplit('-').next().unwrap_or(id);
    let m = json!({
        "id": id, "name": name, "version": "0.1.0", "kind": kind, "engine": "wasm",
        "provides": provides, "abi": abi, "wasm": "addon.wasm",
        "description": format!("{name} addon"), "author": "",
        "permissions": [],
        "capabilities": { "http": [], "secrets": [], "kv": false, "events": [], "cron": [] },
        "settings": []
    });
    serde_json::to_string_pretty(&m).unwrap_or_default() + "\n"
}

const RUST_LIB: &str = r#"//! Generated by `pelty-cli addon wasm-scaffold`.
use pelty_addon_sdk::serde_json;

struct PeltyAddon;
impl pelty_addon_sdk::Guest for PeltyAddon {
    fn describe() -> String {
        serde_json::json!({ "id": "__PROVIDES__", "name": "__NAME__" }).to_string()
    }
    fn call(op: String, _input: String) -> Result<String, String> {
        Err(format!("unknown op {op}"))
    }
    fn on_event(_name: String, _payload: String) -> Result<(), String> {
        Ok(())
    }
}
/// Cron jobs (ABI 0.5, SDK feature `cron`). Declare each job in addon.json,
/// e.g. `"cron": [{ "name": "nightly", "schedule": "0 3 * * *" }]` under
/// `capabilities` (five fields, company time zone; the admin approves the
/// `cron` permission at install and can change the schedule later). Jobs can
/// also be added at runtime with `pelty_addon_sdk::power::cron_register`
/// (set `"cron_runtime": true`). The returned JSON is the run's result.
impl pelty_addon_sdk::ScheduledGuest for PeltyAddon {
    fn on_cron(job: String) -> Result<String, String> {
        match job.as_str() {
            "nightly" => {
                pelty_addon_sdk::log_info("nightly job ran");
                Ok(serde_json::json!({ "ok": true }).to_string())
            }
            other => Err(format!("unknown cron job {other}")),
        }
    }
}
pelty_addon_sdk::export!(PeltyAddon with_types_in pelty_addon_sdk);
"#;

const C_MAIN: &str = r#"// UNTESTED template. Generate bindings first:
//   wit-bindgen c --world pelty-addon path/to/pelty.wit
// then build with wasi-sdk:
//   clang --target=wasm32-wasip2 -mexec-model=reactor -o addon.wasm main.c pelty_addon.c pelty_addon_component_type.o
#include "pelty_addon.h"
#include <string.h>

static void set(pelty_addon_string_t *s, const char *v) { pelty_addon_string_dup(s, v); }

void exports_pelty_addon_addon_describe(pelty_addon_string_t *ret) { set(ret, "{\"id\":\"__PROVIDES__\",\"name\":\"__NAME__\"}"); }

bool exports_pelty_addon_addon_call(pelty_addon_string_t *op, pelty_addon_string_t *input, pelty_addon_string_t *ret, pelty_addon_string_t *err) {
    (void)op; (void)input; (void)ret;
    set(err, "unknown op");
    return false;
}

bool exports_pelty_addon_addon_on_event(pelty_addon_string_t *name, pelty_addon_string_t *payload, pelty_addon_string_t *err) {
    (void)name; (void)payload; (void)err;
    return true;
}
"#;

const GO_MAIN: &str = r#"// UNTESTED template. Generate bindings first:
//   go run go.bytecodealliance.org/cmd/wit-bindgen-go generate -o internal path/to/pelty.wit
// then build:
//   tinygo build -target=wasip2 --wit-package path/to/pelty.wit --wit-world pelty-addon -o addon.wasm .
package main

import (
	"go.bytecodealliance.org/cm"
	addon "__MODULE__/internal/pelty/addon/addon"
)

func init() {
	addon.Exports.Describe = func() string { return `{"id":"__PROVIDES__","name":"__NAME__"}` }
	addon.Exports.Call = func(op string, input string) cm.Result[string, string, string] {
		return cm.Err[cm.Result[string, string, string]]("unknown op " + op)
	}
	addon.Exports.OnEvent = func(name string, payload string) cm.Result[string, struct{}, string] {
		return cm.OK[cm.Result[string, struct{}, string]](struct{}{})
	}
}

func main() {}
"#;

pub fn scaffold(dir: &Path, id: &str, kind: &str, name: &str, lang: &str, sdk: &str) -> Result<PathBuf, String> {
    if !pelty_extensions::addon_pkg::id_ok(id) {
        return Err("id must match [a-z0-9-]{3,64}".into());
    }
    if !LANGS.contains(&lang) {
        return Err(format!("lang must be one of {}", LANGS.join(", ")));
    }
    let d = dir.join(id);
    if d.exists() {
        return Err(format!("{} already exists", d.display()));
    }
    let provides = id.rsplit('-').next().unwrap_or(id);
    let fill = |t: &str| t.replace("__PROVIDES__", provides).replace("__NAME__", name).replace("__MODULE__", id);
    let mut files: Vec<(&str, String)> = vec![("addon.json", manifest(id, kind, name, if lang == "rust" { "0.5.0" } else { "0.4.0" }))];
    match lang {
        "rust" => {
            files.push(("Cargo.toml", format!("[package]\nname = \"{id}\"\nversion = \"0.1.0\"\nedition = \"2021\"\npublish = false\n\n[lib]\ncrate-type = [\"cdylib\"]\n\n[dependencies]\npelty-addon-sdk = {{ path = \"{sdk}\", features = [\"cron\"] }}\n\n[profile.release]\nopt-level = \"s\"\nlto = true\nstrip = true\n")));
            files.push(("src/lib.rs", fill(RUST_LIB)));
            files.push(("README.md", "Build: `cargo build --release --target wasm32-wasip2`, copy the .wasm to `addon.wasm` next to addon.json, then `pelty-cli addon pack .`\n".into()));
        }
        "c" => {
            files.push(("main.c", fill(C_MAIN)));
            files.push(("README.md", "UNTESTED C template (wasi-sdk + wit-bindgen c). See main.c header, then `pelty-cli addon pack .`\n".into()));
        }
        _ => {
            files.push(("main.go", fill(GO_MAIN)));
            files.push(("go.mod", format!("module {id}\n\ngo 1.23\n\nrequire go.bytecodealliance.org/cm v0.3.0\n")));
            files.push(("README.md", "UNTESTED TinyGo template (tinygo >= 0.34, wasip2). See main.go header, then `pelty-cli addon pack .`\n".into()));
        }
    }
    for (p, body) in files {
        let f = d.join(p);
        if let Some(parent) = f.parent() {
            std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        std::fs::write(&f, body).map_err(|e| e.to_string())?;
    }
    Ok(d)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scaffolds_every_lang_with_valid_manifest() {
        let tmp = std::env::temp_dir().join(format!("pelty-wasm-scaffold-{}", std::process::id()));
        for lang in LANGS {
            let id = format!("sso-demo{lang}");
            let d = scaffold(&tmp, &id, "sso", "Demo", lang, "../sdk").unwrap();
            let m: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(d.join("addon.json")).unwrap()).unwrap();
            assert!(crate::lint_manifest(&m).is_empty(), "{lang}");
            assert_eq!(m["engine"], "wasm");
            assert_eq!(m["abi"], if *lang == "rust" { "0.5.0" } else { "0.4.0" });
            assert!(scaffold(&tmp, &id, "sso", "Demo", lang, "../sdk").is_err());
        }
        assert!(scaffold(&tmp, "x", "sso", "Demo", "rust", "../sdk").is_err());
        assert!(scaffold(&tmp, "abc-def", "sso", "Demo", "zig", "../sdk").is_err());
        let _ = std::fs::remove_dir_all(&tmp);
    }
}

#!/usr/bin/env bash
# Regenerate THIRD_PARTY_LICENSES.md (shipped in release archives and the Docker image).
# Needs: cargo-about (`cargo install cargo-about --locked`), pnpm, and frontend deps installed.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"
out="THIRD_PARTY_LICENSES.md"
tmp="$(mktemp)"
{
  echo "# Third-party licenses"
  echo
  echo "PeltyCMS (GNU AGPL v3 or later, see LICENSE) bundles the open source components"
  echo "below. Each keeps its own license. Generated by scripts/third-party-licenses.sh;"
  echo "do not edit by hand."
  echo
  cargo about generate --offline --locked -c about.toml scripts/licenses/about.hbs
  echo
  echo "## Frontend (npm packages bundled into the web UI)"
  echo
  (cd frontend && pnpm licenses list --prod --json) | python3 "$root/scripts/licenses/npm.py"
} > "$tmp"
mv "$tmp" "$out"
chmod 644 "$out"
echo "wrote $out"
